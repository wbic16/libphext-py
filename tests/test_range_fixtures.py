# Shared libphext 0.6.1 range conformance fixtures (see FIXTURES-RANGES.md
# in libphext-rs / the ports-v06 workspace). Every case: parse the input
# bytes, take chain 0 of parse_chains(input), and run every op in
# expected.tsv exactly as the format spec specifies — parse ops check the
# canonical serialization (or the expected error), resolve ops check the
# "<universe>|<coordinate>|<char offset>" digest, and fetch ops compare
# result bytes against results/NN.txt plus the resolved flag (the two
# empty-result situations — resolved-but-empty vs unresolved — stay
# distinguishable). Expectations were generated by libphext-rs 0.6.1
# itself — no value here is hand-computed.
import hashlib
from pathlib import Path

import pytest

from phext import chain
from phext.addressing import parse_point_address, parse_range_address

FIXTURES = Path(__file__).parent / "fixtures" / "ranges"


def _sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _cases():
    index = (FIXTURES / "cases.tsv").read_text(encoding="utf-8").splitlines()
    names = []
    for line in index[1:]:  # header first
        if line.strip():
            names.append(line.split("\t")[0])
    return names


def _read_case(case_name):
    case_dir = FIXTURES / case_name
    lines = (case_dir / "expected.tsv").read_text(encoding="utf-8").splitlines()
    header = {}
    ops = []
    for line in lines:
        fields = line.split("\t")
        if fields[0] == "op":
            ops.append(fields)
        elif len(fields) == 2:
            header[fields[0]] = fields[1]
    return case_dir, header, ops


def _kv(field):
    key, _, value = field.partition("=")
    return key, value


@pytest.mark.parametrize("case_name", _cases())
def test_range_fixture_case(case_name):
    case_dir, header, ops = _read_case(case_name)
    assert header["case"] == case_name
    assert int(header["ops"]) == len(ops), case_name

    data = (case_dir / "input.phext").read_bytes()
    # input identity (catches newline-translating reads immediately)
    assert len(data) == int(header["input_bytes"]), case_name
    assert _sha(data) == header["input_sha256"], case_name

    stream = data.decode("utf-8")
    chain0 = chain.parse_chains(stream)[0]

    for fields in ops:
        kind, address = fields[1], fields[2]
        label = (case_name, kind, address)
        if kind == "parse_point":
            _, canonical = _kv(fields[3])
            _, error = _kv(fields[4])
            result = parse_point_address(address)
            if error == "true":
                assert result is None, label
            else:
                assert result is not None, label
                assert str(result) == canonical, label
        elif kind == "parse_range":
            _, canonical = _kv(fields[3])
            _, error = _kv(fields[4])
            result = parse_range_address(address)
            if error == "true":
                assert result is None, label
            else:
                assert result is not None, label
                assert str(result) == canonical, label
        elif kind == "resolve_point":
            _, resolve = _kv(fields[3])
            _, error = _kv(fields[4])
            point = parse_point_address(address)
            assert point is not None, label
            result = chain0.resolve_point(point)
            if error == "true":
                assert result is None, label
            else:
                assert result is not None, label
                universe, coord, offset = result
                assert f"{universe}|{coord}|{offset}" == resolve, label
        elif kind == "fetch_point":
            _, filename = _kv(fields[3])
            _, resolved = _kv(fields[4])
            expected = (case_dir / filename).read_bytes()
            point = parse_point_address(address)
            is_resolved = (
                point is not None and chain0.resolve_point(point) is not None
            )
            assert is_resolved == (resolved == "true"), label
            result = chain0.fetch_point(address)
            assert result.encode("utf-8") == expected, label
        elif kind == "fetch_range":
            _, filename = _kv(fields[3])
            _, resolved = _kv(fields[4])
            expected = (case_dir / filename).read_bytes()
            range_address = parse_range_address(address)
            is_resolved = (
                range_address is not None
                and chain0.resolve_range(range_address) is not None
            )
            assert is_resolved == (resolved == "true"), label
            result = chain0.fetch_range(address)
            assert result.encode("utf-8") == expected, label
        else:
            raise AssertionError(f"unknown op kind {kind!r} in {case_name}")
